    public void readSettings() {
        String[] names = SPCMapSettings.getInstance().getOutlookNames();
        this.day1Radio.setText(names[0]);
        this.day2Radio.setText(names[1]);
        this.day3Radio.setText(names[2]);
        System.out.println("There are "+names.length+" outlook map type names");
        int size = names.length - 3 +1;
        int index = 1;
        String[] comboBoxModel = new String[size];
        mapComboBox.removeAllItems();
        comboBoxModel[0] = "More Outlooks";
        for (int i=3; i<names.length; i++) {
            comboBoxModel[index] = names[i];
            index++;
        }
        mapComboBox.setModel(new javax.swing.DefaultComboBoxModel<>(comboBoxModel));
      
    }
    private void showOutlookForDay(int num) {
        SPCMap spcMap = new SPCMap(width,height,num);
        
        BufferedImage img = spcMap.getImage();
        imgLabel.setIcon(new ImageIcon(img));
        mapComboBox.setSelectedIndex(0);
    }
