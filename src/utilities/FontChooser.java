    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        if (viewer != null) {
            Properties props = Utilities.readPrefs();
            String isBold = "0";
            if (this.fontBoldCheckbox.isSelected()) {
                isBold = "1";
            }
            props.put("ViewerFont", fontFamilyCombo.getSelectedItem().toString() + "," + isBold + "," + fontSizeCombo.getSelectedItem().toString());
            Utilities.saveMonitorSettingsPrefs(props);
        } else {
            setVisible(false);
        }
    }//GEN-LAST:event_saveButtonActionPerformed

